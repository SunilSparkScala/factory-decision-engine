"""
Downtime robustness analysis.

Repair estimates are uncertain ("6 to 10 hours"), so a recommendation is only useful if we know
how long it stays valid. This re-runs the deterministic decision pipeline across a sweep of
downtime durations and reports where the recommended plan holds and where the best choice changes.
All numbers come from the deterministic orchestrator; nothing here is generated by an LLM.
"""
from typing import Any, Dict, List, Optional, Sequence

MAX_SWEEP_HOURS = 48.0
BASE_SWEEP = [1, 2, 3, 4, 6, 8, 10, 12, 16, 20, 24, 32, 40, 48]


def _sweep_points(downtime: float, downtime_range: Optional[Sequence[float]]) -> List[float]:
    points = set(BASE_SWEEP)
    points.update({downtime, downtime * 0.5, downtime * 1.5, downtime * 2})
    if downtime_range:
        points.update(downtime_range)
    return sorted({round(p, 2) for p in points if 0 < p <= max(MAX_SWEEP_HOURS, downtime)})


def analyze_robustness(
    orchestrator,
    machine_id: str,
    downtime_hours: float,
    priorities: Any,
    constraints: Optional[Dict[str, bool]],
    selected_plan_id: Optional[str],
    downtime_range: Optional[Sequence[float]] = None,
) -> Optional[Dict[str, Any]]:
    """Return a downtime-sensitivity profile for the recommended plan, or None if not applicable."""
    if not machine_id or not selected_plan_id:
        return None

    points: List[Dict[str, Any]] = []
    for hours in _sweep_points(downtime_hours, downtime_range):
        res = orchestrator.orchestrate(
            machine_id=machine_id,
            downtime_hours=hours,
            priorities=priorities,
            constraints=constraints,
        )
        sp = res.selected_plan
        feasible_ids = {c.plan_id for c in res.feasible_alternatives}
        points.append({
            "downtime_hours": hours,
            "best_plan_id": sp.plan_id if sp else None,
            "best_strategy": sp.strategy_type if sp else None,
            "best_description": sp.description if sp else None,
            "best_cost_usd": sp.cost_impact_usd if sp else None,
            "recommended_plan_feasible": selected_plan_id in feasible_ids,
            "recommended_plan_is_best": bool(sp and sp.plan_id == selected_plan_id),
            "delivery_risk": res.impact_summary.get("delivery_risk"),
            "affected_order_count": res.impact_summary.get("affected_order_count"),
        })

    # Contiguous segments of identical best plan, for a "decision map" strip in the UI
    segments: List[Dict[str, Any]] = []
    for p in points:
        if segments and segments[-1]["plan_id"] == p["best_plan_id"]:
            segments[-1]["to_hours"] = p["downtime_hours"]
        else:
            segments.append({
                "plan_id": p["best_plan_id"],
                "strategy": p["best_strategy"],
                "description": p["best_description"],
                "from_hours": p["downtime_hours"],
                "to_hours": p["downtime_hours"],
                "is_recommended": p["best_plan_id"] == selected_plan_id,
            })

    best_hours = [p["downtime_hours"] for p in points if p["recommended_plan_is_best"]]
    infeasible_after = next(
        (p["downtime_hours"] for p in points
         if p["downtime_hours"] > downtime_hours and not p["recommended_plan_feasible"]),
        None,
    )

    lo, hi = (downtime_range or [downtime_hours, downtime_hours])[:2]
    holds_for_range = all(
        p["recommended_plan_is_best"] for p in points if lo <= p["downtime_hours"] <= hi
    )

    if best_hours:
        summary = (
            f"Recommended plan stays the best choice from {min(best_hours):g} h to {max(best_hours):g} h of downtime."
        )
    else:
        summary = "Recommended plan is not the top choice anywhere else in the tested range."
    other = [s for s in segments if not s["is_recommended"] and s["plan_id"]]
    if other:
        alt = other[0]
        summary += (
            f" Between {alt['from_hours']:g} h and {alt['to_hours']:g} h, "
            f"{(alt['strategy'] or '').replace('_', ' ').lower()} ({alt['plan_id']}) is better."
        )
    if infeasible_after is not None:
        summary += f" It becomes infeasible beyond about {infeasible_after:g} h."

    return {
        "selected_plan_id": selected_plan_id,
        "base_downtime_hours": downtime_hours,
        "downtime_range": list(downtime_range) if downtime_range else None,
        "holds_for_stated_range": holds_for_range,
        "best_from_hours": min(best_hours) if best_hours else None,
        "best_to_hours": max(best_hours) if best_hours else None,
        "infeasible_after_hours": infeasible_after,
        "segments": segments,
        "points": points,
        "summary": summary,
    }
